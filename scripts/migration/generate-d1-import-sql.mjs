#!/usr/bin/env node
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';

const IN = process.argv[2] || 'migration/supabase-snapshot.json';
const SQL_OUT = process.argv[3] || 'migration/d1-import.sql';
const LINKS_OUT = process.argv[4] || 'migration/reset-links.json';
const APP_URL = process.env.NEXT_PUBLIC_APP_URL || 'http://localhost:3000';
const PBKDF2_ITERATIONS = 100_000;
const RESET_DAYS = Number(process.env.MIGRATION_RESET_DAYS || 7);

const snapshot = JSON.parse(await readFile(IN, 'utf8'));
const tables = snapshot.tables || {};
const now = new Date().toISOString();
const resetExpiresAt = new Date(Date.now() + RESET_DAYS * 24 * 60 * 60 * 1000).toISOString();
const resetLinks = [];
const activeGuestCountsByExternalLink = new Map();

for (const guest of tables.guests || []) {
  if (!guest.external_link_id || guest.status === 'deleted') continue;
  const count = activeGuestCountsByExternalLink.get(guest.external_link_id) || 0;
  activeGuestCountsByExternalLink.set(guest.external_link_id, count + 1);
}

function sql(value) {
  if (value === undefined || value === null) return 'NULL';
  if (typeof value === 'boolean') return value ? '1' : '0';
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : 'NULL';
  return `'${String(value).replaceAll("'", "''")}'`;
}

function boolInt(value, fallback = true) {
  if (value === undefined || value === null) return fallback ? 1 : 0;
  return value ? 1 : 0;
}

function normalizeRole(role) {
  const value = String(role || 'staff').toLowerCase();
  if (value === 'door') return 'door_staff';
  if (value === 'admin') return 'venue_admin';
  if (['super_admin', 'venue_admin', 'door_staff', 'staff', 'dj'].includes(value)) return value;
  return 'staff';
}

function pbkdf2Hash(plain) {
  const salt = crypto.randomBytes(16);
  const hash = crypto.pbkdf2Sync(plain, salt, PBKDF2_ITERATIONS, 32, 'sha256');
  return `pbkdf2$${PBKDF2_ITERATIONS}$${salt.toString('base64')}$${hash.toString('base64')}`;
}

function resetToken() {
  return crypto.randomBytes(32).toString('base64url');
}

function hashToken(token) {
  return crypto.createHash('sha256').update(token.trim()).digest('hex');
}

function insert(table, values) {
  const cols = Object.keys(values);
  return `INSERT INTO ${table} (${cols.join(', ')}) VALUES (${cols.map((col) => sql(values[col])).join(', ')});`;
}

const lines = [
  '-- Generated by scripts/migration/generate-d1-import-sql.mjs',
  `-- Source exportedAt: ${snapshot.exportedAt || 'unknown'}`,
  `-- Generated at: ${now}`,
  '-- Wrangler D1 execute handles uploaded SQL files atomically.',
  '-- Explicit BEGIN/COMMIT statements are rejected by remote D1.',
  'PRAGMA foreign_keys = ON;',
];

for (const venue of tables.venues || []) {
  lines.push(insert('venues', {
    id: venue.id,
    name: venue.name,
    type: venue.type || 'club',
    address: venue.address || null,
    active: boolInt(venue.active, true),
  }));
}

for (const user of tables.users || []) {
  const token = resetToken();
  const tokenHash = hashToken(token);
  const userId = user.id || crypto.randomUUID();
  const email = String(user.email || '').trim().toLowerCase();
  if (!email) throw new Error(`User ${userId} has no email`);

  lines.push(insert('users', {
    id: userId,
    legacy_auth_user_id: user.auth_user_id || user.legacy_auth_user_id || null,
    email,
    password_hash: pbkdf2Hash(crypto.randomUUID()),
    name: user.name || email,
    role: normalizeRole(user.role),
    venue_id: user.venue_id || null,
    guest_limit: user.guest_limit ?? 10,
    active: boolInt(user.active, true),
    session_version: 0,
    migration_status: 'pending_reset',
    migrated_at: now,
    password_set_at: null,
    created_at: user.created_at || now,
  }));

  lines.push(insert('password_reset_tokens', {
    id: crypto.randomUUID(),
    user_id: userId,
    token: tokenHash,
    expires_at: resetExpiresAt,
    used: 0,
    created_at: now,
  }));

  resetLinks.push({
    userId,
    legacyAuthUserId: user.auth_user_id || null,
    email,
    resetLink: `${APP_URL}/auth/reset-password?token=${token}`,
    expiresAt: resetExpiresAt,
  });
}

for (const link of tables.external_dj_links || []) {
  lines.push(insert('external_dj_links', {
    id: link.id,
    venue_id: link.venue_id,
    token: link.token,
    dj_name: link.dj_name,
    event: link.event || null,
    date: link.date || null,
    max_guests: link.max_guests ?? 10,
    used_guests: activeGuestCountsByExternalLink.get(link.id) || 0,
    active: boolInt(link.active, true),
    expires_at: link.expires_at || null,
    created_by: link.created_by || link.created_by_user_id || null,
    created_at:
      link.created_at ||
      (link.date ? `${link.date}T00:00:00.000Z` : snapshot.exportedAt || now),
  }));
}

for (const guest of tables.guests || []) {
  lines.push(insert('guests', {
    id: guest.id,
    venue_id: guest.venue_id,
    name: guest.name,
    email: guest.email || null,
    instagram: guest.instagram || null,
    external_link_id: guest.external_link_id || null,
    created_by_user_id: guest.created_by_user_id || null,
    terminal_request_id: guest.terminal_request_id || null,
    source: guest.source || 'authon',
    status: guest.status || 'pending',
    check_in_time: guest.check_in_time || null,
    date: guest.date,
    created_at: guest.created_at || now,
    updated_at: guest.updated_at || guest.created_at || now,
  }));
}

lines.push('');

await mkdir(path.dirname(SQL_OUT), { recursive: true });
await writeFile(SQL_OUT, lines.join('\n'));
await writeFile(LINKS_OUT, `${JSON.stringify({ generatedAt: now, resetLinks }, null, 2)}\n`);
console.log(`Wrote ${SQL_OUT}`);
console.log(`Wrote ${LINKS_OUT}`);
console.log(`Rows: venues=${(tables.venues || []).length}, users=${(tables.users || []).length}, external_dj_links=${(tables.external_dj_links || []).length}, guests=${(tables.guests || []).length}`);
