export function translate(
  text: string,
  locale: Locale,
  values: Record<string, string | number> = {},
) {
  let result =
    locale === "en"
      ? (english.get(text) ??
        english.get(text.replace(/\s+/g, " ").trim()) ??
        text)
      : text;
  for (const [key, value] of Object.entries(values))
    result = result.replaceAll(`{${key}}`, String(value));
  return result;
}
